#!/usr/bin/env python3
"""Embeds a text file in a C header as one string: embed_text.py <out.h> <symbol> <in.txt>
(config/GPOE8P/hud_anchor.txt -> hud_anchor_txt.h, read by runtime/src/pso_wide.c)."""
import sys

out, sym, src = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src, encoding="utf-8").read()
lines = ["/* generated by tools/embed_text.py from %s: do not edit */" % src.replace("\\", "/"),
         "static const char %s[] =" % sym]
for line in text.splitlines(True):
    esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    lines.append('    "%s"' % esc)
if len(lines) == 2:
    lines.append('    ""')
lines[-1] += ";"
data = "\n".join(lines) + "\n"
try:
    if open(out, encoding="utf-8").read() == data:
        sys.exit(0)
except OSError:
    pass
open(out, "w", encoding="utf-8").write(data)
